export type ErrorCode =
  | 'INVALID_QR_TOKEN' | 'SESSION_NOT_FOUND' | 'SESSION_CLOSED' | 'TABLE_ALREADY_HAS_OPEN_SESSION'
  | 'MENU_ITEM_UNAVAILABLE' | 'INVALID_QUANTITY' | 'ORDER_ALREADY_PROCESSED' | 'INVALID_STATUS_TRANSITION'
  | 'REJECTION_REASON_REQUIRED' | 'BILL_NOT_FOUND' | 'BILL_ALREADY_CLOSED' | 'BILL_HAS_BALANCE'
  | 'PENDING_ITEMS_REMAIN' | 'PAYMENT_EXCEEDS_BALANCE' | 'DUPLICATE_REQUEST' | 'FORBIDDEN'
  | 'VALIDATION_ERROR' | 'UNAUTHENTICATED' | 'NOT_FOUND' | 'RATE_LIMITED' | 'LOGIN_FAILED' | 'AUTH_SERVICE' | 'INTERNAL';

const STATUS: Record<ErrorCode, number> = {
  INVALID_QR_TOKEN: 404, SESSION_NOT_FOUND: 404, SESSION_CLOSED: 409, TABLE_ALREADY_HAS_OPEN_SESSION: 409,
  MENU_ITEM_UNAVAILABLE: 409, INVALID_QUANTITY: 422, ORDER_ALREADY_PROCESSED: 409, INVALID_STATUS_TRANSITION: 409,
  REJECTION_REASON_REQUIRED: 422, BILL_NOT_FOUND: 404, BILL_ALREADY_CLOSED: 409, BILL_HAS_BALANCE: 409,
  PENDING_ITEMS_REMAIN: 409, PAYMENT_EXCEEDS_BALANCE: 409, DUPLICATE_REQUEST: 409, FORBIDDEN: 403,
  VALIDATION_ERROR: 422, UNAUTHENTICATED: 401, NOT_FOUND: 404, RATE_LIMITED: 429, LOGIN_FAILED: 401, AUTH_SERVICE: 502, INTERNAL: 500,
};

export class AppError extends Error {
  status: number;
  constructor(public code: ErrorCode, message: string, public details: Record<string, unknown> = {}) {
    super(message);
    this.status = STATUS[code];
  }
}
